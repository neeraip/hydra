#!/usr/bin/env python3
"""Benchmark the Hydra CLI end-to-end, across both engines.

For each model this runs the release ``hydra`` binary (parse + full
simulation + summary report) ``--runs`` times after a warm-up and records
the best wall-clock time alongside the model's size. It prints Markdown
tables suitable for pasting into ``docs/src/reference/performance.md``.

Distribution networks come from ``tests/benchmarks/wds/``, which vendors
published ones and generates larger ones (the published suite stops well
short of the sizes where the engines diverge); point ``HYDRA_WDS_CORPUS``
at a directory of ``.inp`` files to time real ones too. Drainage has no suite this repository can redistribute, so
its models are generated by ``scripts/make_uds_benchmark.py`` on demand;
point ``HYDRA_UDS_CORPUS`` at a directory of ``.inp`` files to benchmark
real ones as well.

What the generated drainage models do and do not exercise is worth
knowing. They cover the breadth - hydrology over hundreds of parcels,
dynamic-wave routing, storage, weir, orifice, pump, controls, sanitary
patterns - at a realistic node count, and they surcharge. They do not
reproduce a *stressed* solver: a real network drives the step down with
short channels and transitional flow, where these settle around a
two-second step. A regression in the cost of a step will show here; one
that only bites when the step collapses may not.

Build the binary first, then run:

    cargo build --release -p hydra-cli
    python3 scripts/benchmark.py

Or via just:

    just bench-report

Options:
    --hydra PATH   Path to the hydra binary (default: target/release/hydra)
    --runs N       Timed runs per network, best is reported (default: 5)
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH_DIR = ROOT / "tests" / "benchmarks" / "wds"
UDS_DIR = ROOT / "tests" / "benchmarks" / "uds"

# Slug -> display name. Networks absent from tests/benchmarks/wds/ are skipped.
NETWORKS = [
    ("balerma", "Balerma"),
    ("nytunnels", "NY Tunnels"),
    ("exnet", "Exnet"),
    ("richmond", "Richmond"),
    ("micropolis", "Micropolis"),
    ("dtown", "D-Town"),
    ("ltown", "L-Town"),
    ("ky8", "KY8"),
    ("ky9", "KY9"),
    ("ky10", "KY10"),
    ("bwsn2", "BWSN2"),
    # Generated, written on demand by scripts/make_wds_benchmark.py. The
    # vendored networks stop at 12,500 junctions and the gap against EPANET
    # widens well past that, so the published figures need a size the
    # published networks do not reach.
    ("gen_s", "Generated s"),
    ("gen_m", "Generated m"),
    ("gen_l", "Generated l"),
]


def metadata(hydra: str, inp: Path) -> tuple[int, int, int]:
    """Return (nodes, links, reporting_steps) from the JSON report."""
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / "report.json"
        subprocess.run(
            [hydra, "run", str(inp), "--summary", str(out)],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        data = json.loads(out.read_text())
    i = data["input"]
    nodes = i["junctions"] + i["reservoirs"] + i["tanks"]
    links = i["pipes"] + i["pumps"] + i["valves"]
    report_step = i["report_timestep_s"]
    steps = int(round(i["duration_s"] / report_step)) + 1 if report_step else 1
    return nodes, links, steps


def best_time(hydra: str, inp: Path, runs: int) -> float:
    """Best of `runs` wall-clock seconds for a full run (after one warm-up)."""
    best = None
    for k in range(runs + 1):
        start = time.perf_counter()
        subprocess.run(
            [hydra, "run", str(inp), "-q", "--summary", os.devnull],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        elapsed = time.perf_counter() - start
        if k == 0:  # discard warm-up (warms the OS file cache)
            continue
        best = elapsed if best is None else min(best, elapsed)
    assert best is not None
    return best


def uds_models(hydra: str) -> list[tuple[str, Path, int, int]]:
    """The drainage models to time, as (name, path, nodes, parcels).

    Generated ones are written if absent, so the benchmark is runnable
    from a clean checkout. Anything under `HYDRA_UDS_CORPUS` is timed too,
    with its sizes left unknown: this script will not parse a model to
    find out, and the engine has no JSON summary for drainage to ask.
    """
    sys.path.insert(0, str(ROOT / "scripts"))
    from make_uds_benchmark import SIZES, model  # noqa: PLC0415

    UDS_DIR.mkdir(parents=True, exist_ok=True)
    out: list[tuple[str, Path, int, int]] = []
    for slug in sorted(SIZES):
        trunk, laterals, hours = SIZES[slug]
        path = UDS_DIR / f"bench_{slug}.inp"
        if not path.exists():
            path.write_text(model(trunk, laterals, hours))
        out.append((f"Generated {slug}", path, trunk * (1 + laterals) + 2, trunk * laterals))

    corpus = os.environ.get("HYDRA_UDS_CORPUS")
    if corpus:
        for p in sorted(Path(corpus).glob("*.inp")):
            out.append((p.stem, p, 0, 0))
    return out


def fmt_ms(seconds: float) -> str:
    ms = seconds * 1000.0
    return f"{ms:.0f} ms" if ms >= 10 else f"{ms:.1f} ms"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--hydra", default=str(ROOT / "target" / "release" / "hydra"))
    ap.add_argument("--runs", type=int, default=5)
    args = ap.parse_args()

    if not Path(args.hydra).exists():
        print(
            f"error: {args.hydra} not found — run `cargo build --release -p hydra-cli` first",
            file=sys.stderr,
        )
        return 1

    print("## Water distribution\n")
    # Write the generated networks if absent, so the benchmark runs from a
    # clean checkout the way the drainage half already does.
    sys.path.insert(0, str(ROOT / "scripts"))
    from make_wds_benchmark import SIZES as WDS_SIZES, model as wds_model  # noqa: PLC0415

    BENCH_DIR.mkdir(parents=True, exist_ok=True)
    for slug, (r_, c_, h_) in WDS_SIZES.items():
        path = BENCH_DIR / f"{slug}.inp"
        if not path.exists():
            path.write_text(wds_model(r_, c_, h_))

    targets = list(NETWORKS)
    corpus = os.environ.get("HYDRA_WDS_CORPUS")
    if corpus:
        targets += [(p.stem, p.stem) for p in sorted(Path(corpus).glob("*.inp"))]

    rows = []
    for slug, name in targets:
        inp = BENCH_DIR / f"{slug}.inp"
        if corpus and not inp.exists():
            alt = Path(corpus) / f"{slug}.inp"
            if alt.exists():
                inp = alt
        if not inp.exists():
            print(f"skip: {inp} not found", file=sys.stderr)
            continue
        print(f"benchmarking {name} ...", file=sys.stderr, flush=True)
        nodes, links, steps = metadata(args.hydra, inp)
        elapsed = best_time(args.hydra, inp, args.runs)
        rows.append((name, nodes, links, steps, elapsed))

    rows.sort(key=lambda r: r[1])  # by node count, ascending

    print(f"| Network | Nodes | Links | Steps | Time (best of {args.runs}) |")
    print("|---|--:|--:|--:|--:|")
    for name, nodes, links, steps, elapsed in rows:
        print(f"| {name} | {nodes:,} | {links:,} | {steps:,} | {fmt_ms(elapsed)} |")

    print("\n## Urban drainage\n")
    print(f"| Model | Nodes | Parcels | Time (best of {args.runs}) |")
    print("|---|--:|--:|--:|")
    for name, path, nodes, parcels in uds_models(args.hydra):
        print(f"benchmarking {name} ...", file=sys.stderr, flush=True)
        elapsed = best_time(args.hydra, path, args.runs)
        n = f"{nodes:,}" if nodes else "?"
        p = f"{parcels:,}" if parcels else "?"
        print(f"| {name} | {n} | {p} | {fmt_ms(elapsed)} |")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
